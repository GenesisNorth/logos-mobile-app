"""Fetches the weekly verses in every open-licensed translation from
bible.helloao.org and writes lib/features/journey/data/open_translation_texts.dart.

Usage: python3 tool/fetch_translations.py
When weeks are added, extend REFS (and later move this to the admin content pipeline).
"""
import json, sys, urllib.request, re, time, os
OUT = os.path.join(os.path.dirname(__file__), '..', 'lib', 'features', 'journey', 'data', 'open_translation_texts.dart')
TRANS = {  # app key -> helloao id
 'BSB':'BSB','WEB':'ENGWEBP','LSV':'eng_lsv','LEB':'eng_leb','BBE':'eng_bbe','ASV':'eng_asv',
 'RV':'eng_rv5','GNV':'eng_gnv','DRA':'eng_dra','DBY':'eng_dby','YLT':'eng_ylt','WBS':'eng_wbs','KJV':'eng_kjv'}
REFS = {'John 15:5':('JHN',15,[5]),'Philippians 4:6-7':('PHP',4,[6,7]),'Romans 8:1-2':('ROM',8,[1,2]),
        'Psalm 23:1-3':('PSA',23,[1,2,3]),'Colossians 3:1-3':('COL',3,[1,2,3])}
def text_of(parts):
    bits=[]
    for p in parts:
        if isinstance(p,str): bits.append(p)
        elif isinstance(p,dict) and 'text' in p: bits.append(p['text'])
    return ' '.join(bits)
def clean(t):
    t=re.sub(r'^(A (PSALM|Psalm|psalm|Psalme) (OF|of|for) DAVID\.|A (PSALM|Psalm|psalm|Psalme) (OF|of|for) David\.)\s*','',t)
    t=t.replace('||',' ').replace('⸤','').replace('⸥','')
    t=re.sub(r'\[([^\]]+)\]',r'\1',t)
    t=re.sub(r'\s+',' ',t).strip()
    t=re.sub(r'\s+([,.;:!?’”])',r'\1',t)
    t=re.sub(r'([;:,.])(?=[A-Za-z])',r'\1 ',t)
    t=t.lstrip('“\'"‘ ')
    if t.endswith('”') and t.count('“')==0: t=t[:-1]
    t=re.sub(r'[;,:]$','.',t)
    if t[0].islower(): t=t[0].upper()+t[1:]
    return t
res={}
for key,tid in TRANS.items():
    res[key]={}
    for ref,(book,ch,vs) in REFS.items():
        c=22 if (key=='DRA' and book=='PSA') else ch
        url=f'https://bible.helloao.org/api/{tid}/{book}/{c}.json'
        try:
            d=json.load(urllib.request.urlopen(url,timeout=20))
        except Exception as e:
            res[key][ref]=None; print('ERR',key,ref,e,file=sys.stderr); continue
        verses={x['number']:text_of(x['content']) for x in d['chapter']['content'] if x.get('type')=='verse'}
        got=[verses.get(v) for v in vs]
        res[key][ref]=clean(' '.join(got)) if all(got) else None
        time.sleep(0.1)
esc=lambda t:t.replace('\\','\\\\').replace("'","\\'")
lines=["// GENERATED by tool/fetch_translations.py from bible.helloao.org — do not edit by hand.",
       "// Public-domain / openly licensed translations. Re-run the tool to refresh.","",
       "const Map<String, Map<String, String>> openTranslationTexts = {"]
for r in REFS:
    lines.append(f"  '{r}': {{")
    for k in TRANS:
        if res[k][r] is None: sys.exit(f'missing {k} {r}')
        lines.append(f"    '{k}':\n        '{esc(res[k][r])}',")
    lines.append("  },")
lines.append("};")
open(OUT,'w').write('\n'.join(lines)+'\n')
print('wrote',OUT)
